#!/usr/bin/env python3
"""Build the user-style synthetic ``.mph`` that the G3 chain C case continues from.

What it produces
----------------
One COMSOL model, built **only** through the published MCP operations of the
production stdio entrypoint (``python -m comsol_mcp.mcp_server``), saved as a
``.mph`` plus a JSON receipt:

* a component with **two** geometry sequences: the target ``geom1`` **and a
  sibling** ``geom2`` (a non-target node: a second user geometry the
  continuation must not disturb),
* a constant material on the block **and** a second, unused material in the
  tree (non-target node),
* a heat-transfer physics interface with a user boundary condition **and** a
  second heat-transfer interface that is switched off in the study step
  (non-target nodes),
* a mesh (built, with statistics) with its global size edited by hand,
* a transient study with the exact tags chain C targets: study ``std1`` and
  step ``time`` (``--study-tag``/``--step-tag`` are validated against those
  requirements, never silently defaulted to something else),
* a solver sequence generated by ``study.solver_generate`` (``createAutoSequences``)
  that is then **edited by hand** through ``solver.feature_update`` so a
  continuation must preserve it rather than regenerate it,
* the result nodes a user model carries - a Derived Values node, a Table and
  their data association - created through the published trusted-code operation
  (``code.execute_java`` / ``operation_call``) when the deployment enables it, and
* a solution (unless ``--skip-solve``), because a user-style continuation model
  normally carries one.

Every property value is finally typed from the *engine's own* property
metadata: the builder creates a node, reads ``node.property_schema`` for the
node it wants to set, and only then writes it (``*_update``).  Where the engine
publishes no metadata for a name that the *operation itself* types from a
documented table (a ``Common`` material's ``def`` group), the value is written
through that documented route and the receipt records
``value_source: "documented_table"``; a name that is neither in the engine's
enumeration nor documented is still refused.  Which property of a feature to
write is always read from the engine's own enumeration (``Tinit`` on a heat
transfer ``init`` feature, for example) - never guessed from a remembered name.

Honest limits (recorded, never synthesised)
-------------------------------------------
* The result nodes are reachable only through the trusted-code route: the
  published G3 surface has no derived-value/table operation.  The builder
  therefore *describes* ``code.execute_java`` through ``operation_describe``,
  reads the session's ``trusted_code`` permission off the connect payload, and
  checks whether the result operations are implemented; when any of the three
  facts is missing the step is recorded as ``EXTERNALLY_BLOCKED`` (exit code 4
  unless ``--allow-missing-result-nodes``) with the blocker in
  ``external_blockers``.  No node is ever claimed without an engine readback.
* A failing optional step (solve, manual solver edit, result nodes) never
  turns into a PASS anywhere in the receipt.
* This script never starts, stops or otherwise manages COMSOL, and never
  modifies ``tools/phase4_run_mcp.py``; it imports that driver read-only and
  reuses its ``ProductionHost``/``ActionClient``/``_execution`` conventions so
  the fixture and the acceptance driver speak the same wire dialect.

Offline use
-----------
``--help``, ``--dry-run`` (prints the plan, touches no engine and writes no
file), ``--self-check`` (replays the pure decisions on the metadata recorded
from the failed v11 build and prints the result as JSON),
``--missing-dependency-plan`` / ``--inspect-missing-dependency`` /
``--missing-dependency-donor`` (the T034 missing-dependency fixture: its
reproducible step list, an offline validator that tells a real container apart
from the recorded text probe, and an offline producer that patches a donor
container COMSOL wrote) and ``--handshake-only`` (spawns the stdio child,
initializes, lists tools, writes a receipt, calls no model operation) all work
without a COMSOL Server.
"""
