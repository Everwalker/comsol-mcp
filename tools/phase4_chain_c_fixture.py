    def collect_tree(self, data: Mapping[str, Any]) -> list[dict[str, Any]]:
        """Flatten the ``features``/``children``/``steps`` trees the G3 read operations return."""
        rows: list[dict[str, Any]] = []

        def walk(item: Any) -> None:
            if not isinstance(item, Mapping):
                return
            if item.get("tag"):
                rows.append(dict(item))
            for child in item.get("children", []) if isinstance(item.get("children"), list) else []:
                walk(child)

        for key in ("features", "children", "steps"):
            value = data.get(key)
            if isinstance(value, list):
                for item in value:
                    walk(item)
        return rows

    def collect_solver_features(self, data: Mapping[str, Any]) -> list[dict[str, Any]]:
        """Flatten the node tree returned by ``solver.inspect`` (depth 4)."""
        return self.collect_tree(data)

    async def apply_manual_solver_edit(self, solver_tag: str | None, features: Sequence[Mapping[str, Any]]) -> None:
        driver, args = self.driver, self.args
        candidates: list[tuple[str, str, Any]] = list(args.solver_edit or DEFAULT_SOLVER_EDITS)
        self.solver_edit = {"attempted": True, "applied": False, "solver": solver_tag,
                            "candidates": [{"feature_type": row[0], "property": row[1], "value": row[2]}
                                           for row in candidates],
                            "observed_features": [{"tag": row.get("tag"), "type_id": row.get("type_id")}
                                                  for row in features],
                            "attempts": []}
        if not solver_tag:
            self.solver_edit["reason"] = "no solver sequence is attached to the study"
            self.record("manual_solver_edit", "solver.feature_update", None, status="SKIPPED",
                        notes=self.solver_edit["reason"])
            return
        for feature_type, property_name, value in candidates:
            row = next((item for item in features if item.get("type_id") == feature_type and item.get("tag")), None)
            if row is None:
                self.solver_edit["attempts"].append({"feature_type": feature_type, "property": property_name,
                                                     "status": "FEATURE_NOT_PRESENT"})
                continue
            path = self.path(("sol", solver_tag), ("feature", str(row.get("tag"))))
            schema = await self.read_schema(path, (property_name,), key=f"fixture-solver-schema-{feature_type}")
            metadata = schema.get(property_name)
            if metadata is None:
                self.solver_edit["attempts"].append({"feature_type": feature_type, "tag": row.get("tag"),
                                                     "property": property_name, "status": "PROPERTY_NOT_EXPOSED"})
                continue
            coerced, refusal = self.coerce(value, metadata, property_name)
            if refusal:
                self.solver_edit["attempts"].append({"feature_type": feature_type, "tag": row.get("tag"),
                                                     "property": property_name, "status": "NOT_WRITABLE",
                                                     "reason": refusal})
                continue
            payload = await self.action("solver.feature_update",
                                        {"path": path, "properties": {property_name: coerced}},
                                        key=f"fixture-solver-edit-{feature_type}")
            driver_data = driver._data(payload)
            status = str(driver_data.get("status") or ("APPLIED" if driver._success(payload) else "FAILED"))
            attempt = {"feature_type": feature_type, "tag": row.get("tag"), "path": path,
                       "property": property_name, "requested": coerced, "engine_metadata": driver._json_safe(metadata),
                       "status": status, "error_code": driver._error_code(payload)}
            self.solver_edit["attempts"].append(attempt)
            if driver._success(payload) and status == "APPLIED":
                readback = await self.action("node.property_get", {"path": path, "names": [property_name]},
                                             key=f"fixture-solver-readback-{feature_type}")
                attempt["readback"] = driver._json_safe(driver._data(readback))
                self.solver_edit.update({"applied": True, "feature_type": feature_type, "tag": row.get("tag"),
                                         "path": path, "property": property_name, "value": coerced})
                self.record("manual_solver_edit", "solver.feature_update", payload,
                            notes=f"hand-edited {feature_type} feature {row.get('tag')!r}: {property_name}={coerced!r}",
                            extra={"path": path, "property": property_name, "value": coerced,
                                   "readback": attempt.get("readback")})
                return
            self.record("manual_solver_edit", "solver.feature_update", payload,
                        notes=f"candidate {feature_type}.{property_name} was refused; trying the next candidate",
                        extra={"path": path})
        self.solver_edit["reason"] = "no candidate solver property could be written"
        self.record("manual_solver_edit", "solver.feature_update", None,
                    status="FAILED" if not args.allow_no_manual_solver else "SKIPPED",
                    notes="no manual solver edit could be applied; the saved sequence is not hand-edited")

    def published_trusted_code_tool(self) -> str | None:
        """Return a *published static* trusted-code tool name, or ``None``.

        This is one of the three facts the result-node route records, and it is
        read off the live session inventory, never invented.  The route does *not*
        depend on it: the G3 domain surface is narrower than the implemented
        operation set, so ``code.execute_java`` is reachable through the published
        ``operation_call`` fallback even when no static tool of that name is in
        the tool profile (this build publishes 65 tools and not one of them
        executes Java).
        """
        names = sorted(getattr(self.host, "tools", {}) or {})
        matches = [name for name in names
                   if any(hint in name.lower() for hint in TRUSTED_CODE_HINTS)
                   or ("code" in name.lower() and ("execute" in name.lower() or "java" in name.lower()))]
        return matches[0] if matches else None

    async def attempt_result_nodes(self) -> None:
        """Create the user-style Derived Values/Table nodes and their association.

        The required model feature is a *result node*: a Derived Values node, a
        Table and the data association between them (see the chain C acceptance
        line ``derived_values_and_data_association_preserved``).  The route is the
        published trusted-code operation ``code.execute_java``; the step never
        fakes the node and never reports a pass it did not observe:

        * the route is decided from three recorded facts - the operation's own
          describe status, the session's ``trusted_code`` permission (an operator
          opt-in) and whether the result operations are implemented at all;
        * when any of them is missing the step is recorded as
          ``EXTERNALLY_BLOCKED`` with the blocker in ``external_blockers`` (callers
          that only need the rest of the user-style model pass
          ``--allow-missing-result-nodes``);
        * when the route is available the Java source is dispatched through
          ``operation_call`` and the created tags come from the engine's own
          readback.
        """
        driver, args = self.driver, self.args
        inventory = await self.action("node.find", {
            "query": {}, "root": {"segments": []}, "limit": 500,
            "budget": {"max_nodes": 5000, "max_seconds": 30.0}}, key="fixture-node-find")
        results = [dict(row) for row in driver._data(inventory).get("results", []) if isinstance(row, Mapping)]
        numerical = [row for row in results
                     if any(str(segment.get("collection")) == "numerical"
                            for segment in (row.get("path", {}) or {}).get("segments", [])
                            if isinstance(segment, Mapping))]
        observed = {
            "numerical_nodes_observed": [{"tag": row.get("tag"), "type_id": row.get("type_id")}
                                         for row in numerical],
            "model_nodes_visited": driver._data(inventory).get("visited"),
            "published_trusted_code_tool": self.published_trusted_code_tool(),
            "published_tool_count": len(getattr(self.host, "tools", {}) or {}),
        }

        described = await self.action("operation_describe", {"operation_id": TRUSTED_CODE_OPERATION},
                                      key="fixture-describe-trusted-code")
        describe_data = driver._data(described)
        describe_entry = describe_data.get("entry") if isinstance(describe_data.get("entry"), Mapping) else {}
        describe_status = describe_entry.get("status") or describe_data.get("status")
        if not driver._success(described):
            describe_status = None
        result_status: dict[str, str] = {}
        for operation_id in RESULT_NODE_OPERATIONS:
            row = await self.action("operation_describe", {"operation_id": operation_id},
                                    key=f"fixture-describe-{operation_id.replace('.', '-')}")
            entry = driver._data(row).get("entry")
            entry = entry if isinstance(entry, Mapping) else {}
            result_status[operation_id] = str(entry.get("status") or driver._data(row).get("status") or
                                              ("NOT_DESCRIBED" if not driver._success(row) else "UNKNOWN"))
        route = resolve_trusted_code_route(
            describe_status=describe_status,
            trusted_code_enabled=(self.routing.get("session") or {}).get("trusted_code_enabled"),
            published_tools=getattr(self.host, "tools", {}) or {},
            profile=self.environment.get("tool_profile") or "unknown",
            result_operations=result_status)
        route["described"] = driver._json_safe(describe_data) or None
        self.routing["result_nodes"] = route

        if not args.with_result_nodes:
            self.result_nodes = {"mode": "not_requested", "requested": False, "route": route, **observed}
            self.record("result_nodes", "code execution", None, status="SKIPPED",
                        notes="--no-result-nodes was passed; no result node is claimed",
                        extra={"numerical_nodes_observed": observed["numerical_nodes_observed"]})
            return

        if not route["available"]:
            reason = ("the result nodes (Derived Values + Table + association) need the trusted-code route "
                      f"{route['route']}, which this deployment blocks: "
                      + "; ".join(f"{item['kind']}={item.get('observed') or item.get('operations') or ''}"
                                  for item in route["blockers"]))
            blocker = {"step": "result_nodes", "kind": "result_nodes_unavailable",
                       "route": route["route"], "blockers": route["blockers"],
                       "source_artifact": RESULT_NODE_SOURCE, "entrypoint": RESULT_NODE_ENTRYPOINT,
                       "reason": reason,
                       "minimum_unblock": [
                           f"enable trusted code before the daemon starts: "
                           f"{TRUSTED_CODE_ENV}=1 (the session then reports trusted_code.enabled=true)",
                           "implement the published result operations "
                           f"{list(RESULT_NODE_OPERATIONS)} so a non-code route also exists; "
                           "checking whether a route exists is `operation_describe`",
                       ]}
            self.external_blockers.append(blocker)
            self.result_nodes = {"mode": "externally_blocked", "requested": True, "created": False,
                                 "route": route, "blocker": blocker, **observed}
            self.warn(f"result nodes: {reason}")
            self.record("result_nodes", "code execution", None, status="EXTERNALLY_BLOCKED",
                        notes=f"{reason}; no Derived Values node is claimed",
                        extra={"blockers": route["blockers"], "source_artifact": RESULT_NODE_SOURCE,
                               "numerical_nodes_observed": observed["numerical_nodes_observed"]})
            return

        source = ROOT / RESULT_NODE_SOURCE
        source_sha = driver._sha256(source) if source.is_file() else None
        if not source.is_file():
            reason = f"the Java source {RESULT_NODE_SOURCE} is missing"
            self.result_nodes = {"mode": "skipped", "reason": reason, "requested": True,
                                 "route": route, **observed}
            self.record("result_nodes", TRUSTED_CODE_OPERATION, None, status="SKIPPED", notes=reason)
            return
        payload = await self.operation_call(TRUSTED_CODE_OPERATION, {
            "source_artifact": RESULT_NODE_SOURCE, "entrypoint": RESULT_NODE_ENTRYPOINT,
            "arguments": {"dataset": f"dset_{args.study_tag}", "expression": "T",
                          "numerical_tag": "cder1", "table_tag": "ctbl1"},
            "mode": "trusted", "invariants": []}, key="fixture-result-nodes")
        data = driver._data(payload)
        readback = data.get("readback") if isinstance(data.get("readback"), Mapping) else {}
        if driver._success(payload):
            self.result_nodes = {"mode": "code", "route": route, "created": True,
                                 "source_artifact": RESULT_NODE_SOURCE,
                                 "source_sha256": source_sha, "entrypoint": RESULT_NODE_ENTRYPOINT,
                                 "created_nodes": driver._json_safe(readback.get("created")),
                                 "readback": driver._json_safe(readback) or None,
                                 "requested": True, **observed}
            self.record("result_nodes", TRUSTED_CODE_OPERATION, payload,
                        notes=f"trusted Java created the result nodes through {route['route']}; the tags are "
                              f"the engine's own readback",
                        extra={"created_nodes": self.result_nodes["created_nodes"]})
            return
        reason = (f"{TRUSTED_CODE_OPERATION} returned {driver._error_code(payload) or 'an invalid envelope'}: "
                  f"{driver._error_message(payload) or 'no message'}")
        after = await self.action("node.find", {
            "query": {}, "root": {"segments": []}, "limit": 500,
            "budget": {"max_nodes": 5000, "max_seconds": 30.0}}, key="fixture-node-find-after")
        after_rows = [dict(row) for row in driver._data(after).get("results", []) if isinstance(row, Mapping)]
        numerical_after = [{"tag": row.get("tag"), "type_id": row.get("type_id")} for row in after_rows
                           if any(str(segment.get("collection")) == "numerical"
                                  for segment in (row.get("path", {}) or {}).get("segments", [])
                                  if isinstance(segment, Mapping))]
        blocker = {"step": "result_nodes", "kind": "result_node_execution_failed",
                   "route": route["route"], "error_code": driver._error_code(payload), "reason": reason}
        self.external_blockers.append(blocker) if not args.allow_missing_result_nodes else None
        self.result_nodes = {"mode": "failed", "reason": reason, "requested": True, "created": False,
                             "route": route, "error_code": driver._error_code(payload),
                             "numerical_nodes_observed": numerical_after, **observed}
        self.warn(f"result nodes: {reason}")
        self.record("result_nodes", TRUSTED_CODE_OPERATION, payload,
                    status="FAILED" if not args.allow_missing_result_nodes else "SKIPPED",
                    notes=f"{reason}; no Derived Values node is claimed",
                    extra={"numerical_nodes_observed": numerical_after})

    async def verify(self) -> None:
        """Read the live model back: the structure chain C depends on must be present."""
        driver = self.driver
        checks: dict[str, Any] = {}

        study = await self.action("study.inspect", {"path": self.study_path}, key="fixture-verify-study")
        study_data = driver._data(study)
        steps = self.collect_tree(study_data)
        checks["study"] = {"success": driver._success(study), "tag": self.args.study_tag,
                           "steps": [{"tag": row.get("tag"), "type_id": row.get("type_id")} for row in steps],
                           "target_step_present": any(str(row.get("tag")) == self.args.step_tag for row in steps)}
        self.record("verify", "study.inspect", study,
                    extra={"target_step_present": checks["study"]["target_step_present"]})

        tlist = await self.action("node.property_get", {"path": self.study_step_path, "names": ["tlist"]},
                                  key="fixture-verify-tlist")
        checks["tlist"] = driver._json_safe(driver._data(tlist))
        self.record("verify", "node.property_get", tlist, extra={"property": "tlist"})

        solvers = await self.action("solver.list", {"filter": {"study": self.args.study_tag}},
                                    key="fixture-verify-solvers")
        checks["solvers"] = [{"solver": row.get("solver"), "study": row.get("study"),
                              "feature_count": row.get("feature_count")}
                             for row in driver._data(solvers).get("solvers", []) if isinstance(row, Mapping)]
        self.record("verify", "solver.list", solvers)

        physics = await self.action("physics.list", {"component": self.args.component}, key="fixture-verify-physics")
        checks["physics"] = driver._json_safe(driver._data(physics))
        self.record("verify", "physics.list", physics)

        materials = await self.action("material.list", {"component": self.args.component}, key="fixture-verify-materials")
        checks["materials"] = driver._json_safe(driver._data(materials))
        self.record("verify", "material.list", materials)

        self.verification = checks
        required = [checks["study"].get("success"), checks["study"].get("target_step_present"),
                    bool(checks["solvers"]), driver._success(tlist)]
        if not all(required):
            self.warn("post-save verification did not observe the full required structure; see verification in the receipt")

    def status(self) -> int:
        required = {"model_create", "component_create", "geometry_create", "geometry_build",
                    "material_target", "physics_create", "mesh_create", "mesh_build",
                    "study_create", "study_step_transient", "study_step_tlist",
                    "study_solver_generate", "model_save"}
        failed = [row for row in self.steps if row["step"] in required and not row["success"]]
        blocked = [row for row in self.steps if row["status"] == "BLOCKED"]
        if blocked:
            return 3
        if failed:
            return 1
        if not self.solver_edit.get("applied") and not self.args.allow_no_manual_solver:
            return 1
        # An external blocker is a distinct outcome: the model is complete except
        # for the part the *deployment* forbids (the result nodes need the
        # trusted-code route).  It is exit 4 rather than a silent 0 so a recorded
        # run cannot be read as "the required model feature is present".
        if self.external_blockers and not self.args.allow_missing_result_nodes:
            return 4
        return 0

