def validate(args: argparse.Namespace, parser: argparse.ArgumentParser) -> None:
    """Refuse a fixture the chain C case could not use (fail closed, before any engine call)."""
    if args.study_tag != REQUIRED_STUDY_TAG:
        parser.error(f"--study-tag must be {REQUIRED_STUDY_TAG!r}: the chain C case targets that study")
    if args.step_tag != REQUIRED_STEP_TAG:
        parser.error(f"--step-tag must be {REQUIRED_STEP_TAG!r}: the chain C case targets that step")
    for tag, label in ((args.component, "--component"), (args.geometry_tag, "--geometry-tag"),
                       (args.sibling_geometry_tag, "--sibling-geometry-tag"),
                       (args.mesh_tag, "--mesh-tag"), (args.physics_tag, "--physics-tag"),
                       (args.second_physics_tag, "--second-physics-tag"), (args.material_tag, "--material-tag"),
                       (args.second_material_tag, "--second-material-tag")):
        if not tag or not tag.replace("_", "").isalnum():
            parser.error(f"{label} must be a plain COMSOL tag")
    if args.component == args.geometry_tag:
        parser.error("--component and --geometry-tag must differ")
    if len({args.geometry_tag, args.sibling_geometry_tag, args.mesh_tag}) != 3:
        parser.error("--geometry-tag, --sibling-geometry-tag and --mesh-tag must differ")
    if args.material_tag == args.second_material_tag:
        parser.error("--material-tag and --second-material-tag must differ")
    if args.physics_tag == args.second_physics_tag:
        parser.error("--physics-tag and --second-physics-tag must differ")
    if args.length <= 0 or args.width <= 0 or args.height <= 0:
        parser.error("--length/--width/--height must be positive")
    if not 1 <= args.mesh_size_level <= 9:
        parser.error("--mesh-size-level must be between 1 and 9")
    if args.solve_timeout_s <= 0:
        parser.error("--solve-timeout-s must be positive")
    if not 1 <= args.port <= 65535:
        parser.error("--port must be between 1 and 65535")
    if args.with_derived_value and not args.with_result_nodes:
        parser.error("--with-derived-value cannot be combined with --no-result-nodes")
    offline_actions = [name for name, chosen in (("--dry-run", args.dry_run), ("--self-check", args.self_check),
                                                ("--missing-dependency-plan", args.missing_dependency_plan),
                                                ("--inspect-missing-dependency",
                                                 args.inspect_missing_dependency is not None),
                                                ("--missing-dependency-donor",
                                                 args.missing_dependency_donor is not None))
                       if chosen]
    if len(offline_actions) > 1:
        parser.error("choose one offline action, not " + ", ".join(offline_actions))
    if args.missing_dependency_out is not None and args.missing_dependency_donor is None:
        parser.error("--missing-dependency-out needs --missing-dependency-donor")
    if args.missing_dependency_donor is not None and args.missing_dependency_out is None:
        parser.error("--missing-dependency-donor needs --missing-dependency-out <dir>")
    if args.missing_dependency_source is not None and args.missing_dependency_donor is None:
        parser.error("--missing-dependency-source needs --missing-dependency-donor")
    if args.handshake_only and (args.live or offline_actions):
        parser.error("--handshake-only cannot be combined with --live or any offline action")
    if not args.live and not args.handshake_only and not offline_actions:
        parser.error("pass --live to build the fixture, --dry-run to print the plan, --self-check for the "
                     "offline self-check, --missing-dependency-plan / --inspect-missing-dependency / "
                     "--missing-dependency-donor for the T034 fixture, or --handshake-only")


