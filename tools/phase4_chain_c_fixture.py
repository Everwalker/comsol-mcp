    async def run(self, *, handshake_only: bool = False) -> int:
        driver, driver_args = self.driver, self.driver_args
        self.run_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
        self.environment = {
            "python": str(driver_args.python),
            "host": str(driver_args.host),
            "port": int(driver_args.port),
            "comsol_root": str(driver_args.comsol_root) if driver_args.comsol_root else None,
            "jdk11": str(driver_args.jdk11) if driver_args.jdk11 else None,
            "prefs": str(driver_args.prefs) if driver_args.prefs else None,
            "tool_profile": driver_args.tool_profile,
            "private_home": str(driver_args.private_home) if driver_args.private_home else None,
            "run_dir": str(self.run_dir),
            "output": str(self.output),
            "started_at": _utc_now(),
            "isolation_receipt_present": bool(os.environ.get("COMSOL_MCP_ISOLATION_RECEIPT")),
            "comsol_lifecycle": "not managed by this script (no COMSOL start/stop)",
        }
        exit_code = 3
        startup_error: str | None = None
        host = driver.ProductionHost(driver_args, self.run_dir, self.transcript, label="primary")
        self.host = host
        started = time.monotonic()
        try:
            async with host:
                self.environment["tool_count"] = len(host.tools)
                print(f"  .. stdio session ready: {len(host.tools)} tools, "
                      f"private home {host.private_home}")
                if handshake_only:
                    self.record("handshake", "initialize + tools/list", {"success": True},
                                status="APPLIED", extra={"initialize": host.initialize_summary()})
                    exit_code = 0
                else:
                    client = driver.ActionClient(host, driver_args, self.state)
                    try:
                        exit_code = await self.build(host, client)
                    except FixtureBlocked as exc:
                        # Handled inside the session block so the stdio child is
                        # torn down cleanly instead of through an exception group.
                        startup_error = f"blocked: {exc}"
                        exit_code = 3
                        self.record("fixture", "blocked capability", None, status="BLOCKED",
                                    notes=startup_error)
        except FixtureBlocked as exc:
            startup_error = f"blocked: {exc}"
            exit_code = 3
            self.record("session", "stdio session", None, status="BLOCKED", notes=startup_error)
        except BaseException as exc:  # noqa: BLE001 - the receipt records any driver-side failure
            startup_error = f"{type(exc).__name__}: {exc}"
            exit_code = 1
            self.record("session", "stdio session", None, status="FAILED", notes=startup_error)
        finally:
            elapsed = round(time.monotonic() - started, 3)
            self.environment["elapsed_s"] = elapsed
            self.environment["self_test"] = self_consistency()
            self._write_evidence(exit_code, startup_error)
        return exit_code

    def _write_evidence(self, exit_code: int, startup_error: str | None) -> None:
        driver = self.driver
        driver._write_json(self.run_dir / "transcript.json", {
            "transport": "stdio", "host": "primary", "call_count": len(self.transcript),
            "transcript": self.transcript})
        driver._write_json(self.receipt_path, self.receipt(exit_code=exit_code, startup_error=startup_error))
        driver._write_json(self.run_dir / "environment.json", self.environment)
        sums = []
        for path in sorted(self.run_dir.glob("*")):
            if path.is_file():
                sums.append({"path": path.name, "bytes": path.stat().st_size, "sha256": driver._sha256(path)})
        driver._write_json(self.run_dir / "SHA256SUMS.json", {"files": sums})
        print(f"  .. receipt: {self.receipt_path}")


