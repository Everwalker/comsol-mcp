class ChainCFixture:
    """One stdio session, one build plan, one receipt."""

    def __init__(self, args: argparse.Namespace, driver: Any, driver_args: argparse.Namespace) -> None:
        self.args = args
        self.driver = driver
        self.driver_args = driver_args
        self.run_dir = Path(args.run_dir).expanduser()
        self.output = Path(args.output).expanduser() if args.output else self.run_dir / "chain_c_user_style.mph"
        self.receipt_path = self.run_dir / "chain_c_fixture_receipt.json"
        self.transcript: list[dict[str, Any]] = []
        self.state: dict[str, Any] = {"ref": None, "revision": None, "model_label": None}
        self.steps: list[dict[str, Any]] = []
        self.warnings: list[str] = []
        self.environment: dict[str, Any] = {}
        self.host: Any = None
        self.client: Any = None
        #: Monotonic per-call counter.  Every published call gets its own
        #: idempotency key: reusing a key with a different body (a different
        #: revision after a write) is refused by the control plane with
        #: IDEMPOTENCY_CONFLICT, which the v11 build hit when it re-read a
        #: schema under the key it had already used.
        self.call_sequence = 0
        self.routing: dict[str, Any] = {}
        self.solver_edit: dict[str, Any] = {"attempted": False, "applied": False, "candidates": []}
        self.initial_values: dict[str, Any] = {"attempted": False, "written": None}
        self.mesh_size: dict[str, Any] = {"tag": None, "rule": None}
        self.result_nodes: dict[str, Any] = {
            "mode": "not_reached",
            "reason": "the build did not reach the result-node step"}
        self.sibling_geometry: dict[str, Any] = {"attempted": False, "applied": False}
        self.external_blockers: list[dict[str, Any]] = []
        self.tlist: dict[str, Any] = {}
        self.verification: dict[str, Any] = {}

    # -- bookkeeping ------------------------------------------------------

    def record(self, step: str, operation: str, payload: Mapping[str, Any] | None,
               *, status: str | None = None, notes: str | None = None,
               extra: Mapping[str, Any] | None = None) -> dict[str, Any]:
        driver = self.driver
        row: dict[str, Any] = {
            "step": step,
            "operation": operation,
            "success": bool(driver._success(payload)) if payload is not None else False,
            "error_code": driver._error_code(payload) if payload is not None else None,
            "status": status or ("APPLIED" if payload is not None and driver._success(payload) else "FAILED"),
            "outer_isError": payload.get("_outer_isError") if isinstance(payload, Mapping) else None,
            "notes": notes,
        }
        if extra:
            row.update(extra)
        self.steps.append(driver._json_safe(row))
        marker = "ok " if row["success"] or row["status"] in {"APPLIED", "SKIPPED", "INFO"} else "!! "
        detail = row["error_code"] or row["status"]
        print(f"  {marker}{step:<28} {operation:<48} {detail}")
        if row["notes"]:
            print(f"      {row['notes']}")
        return row

    def warn(self, message: str) -> None:
        self.warnings.append(message)
        print(f"  ~~ warning: {message}")

    # -- small helpers ----------------------------------------------------

    def path(self, *segments: Sequence[str]) -> dict[str, Any]:
        return {"segments": [{"collection": collection, "tag": tag} for collection, tag in segments]}

    @property
    def component_path(self) -> dict[str, Any]:
        return self.path(("component", self.args.component))

    @property
    def geometry_path(self) -> dict[str, Any]:
        return self.path(("component", self.args.component), ("geom", self.args.geometry_tag))

    @property
    def mesh_path(self) -> dict[str, Any]:
        return self.path(("component", self.args.component), ("mesh", self.args.mesh_tag))

    @property
    def physics_path(self) -> dict[str, Any]:
        return self.path(("component", self.args.component), ("physics", self.args.physics_tag))

    @property
    def study_path(self) -> dict[str, Any]:
        return self.path(("study", self.args.study_tag))

    @property
    def study_step_path(self) -> dict[str, Any]:
        return self.path(("study", self.args.study_tag), ("feature", self.args.step_tag))

    @property
    def material_path(self) -> dict[str, Any]:
        return self.path(("component", self.args.component), ("material", self.args.material_tag))

    def dispatch_key(self, stem: str) -> str:
        """Return the idempotency key for the *next* published call.

        The readable ``stem`` labels the logical request in the receipt and the
        driver's transcript; the dispatched key gets the session call counter
        appended so no two calls - not even a schema read before and after a
        write, whose bodies differ only by revision - share a key.  Reusing a key
        with a different body is refused by the control plane with
        IDEMPOTENCY_CONFLICT, which the v11 build hit when it re-read a schema
        under the key it had already used.
        """
        return f"{stem}-{self.call_sequence:03d}"

    async def action(self, operation: str, body: Mapping[str, Any] | None = None, *, key: str) -> dict[str, Any]:
        """Call one published operation with a unique idempotency key."""
        assert self.client is not None
        self.call_sequence += 1
        unique = self.dispatch_key(key)
        try:
            return await self.client.action(operation, dict(body or {}), key=unique, request=key)
        except self.driver.CapabilityUnavailable as exc:
            print(f"  !! {operation:<48} capability unavailable: {exc}")
            return self.driver._synthetic_blocked(operation, str(exc))

    async def operation_call(self, operation_id: str, arguments: Mapping[str, Any], *, key: str) -> dict[str, Any]:
        """Dispatch a *logical* operation through the published ``operation_call`` route.

        The G3 domain surface is narrower than the implemented operation set: a
        logical operation such as ``code.execute_java`` is callable through the
        published fallback even when no static MCP tool of that name is in the
        tool profile.  The nested body is validated by the control plane against
        the same catalogue, so an unimplemented operation is refused there.
        """
        return await self.action("operation_call",
                                 {"operation_id": operation_id, "arguments": dict(arguments)}, key=key)

    async def read_schema(self, path: Mapping[str, Any], names: Iterable[str] | None, *, key: str) -> dict[str, Any]:
        """Read the engine's own property metadata for the requested names.

        ``names`` ``None`` returns the engine's *complete* enumeration, which is
        what a caller needs when it must pick a property by the engine's own
        vocabulary instead of by a name it hopes exists.
        """
        payload = await self.action("node.property_schema", {"path": dict(path)}, key=key)
        rows = [dict(row) for row in self.driver._data(payload).get("properties", [])
                if isinstance(row, Mapping) and isinstance(row.get("name"), str)]
        wanted = None if names is None else {str(name) for name in names}
        return {row["name"]: row for row in rows if wanted is None or row["name"] in wanted}

    def coerce(self, value: Any, row: Mapping[str, Any], label: str) -> tuple[Any, str | None]:
        """Return ``(raw wire value, refusal)`` from the engine's own metadata.

        The G3 write operations take the *raw* value and type it from the target
        node's metadata themselves.  ``int64`` is deliberately refused: the
        published layer has no verified int64 setter, so guessing one here would
        move an unverified conversion into the fixture.
        """
        kind, rank = row.get("kind"), row.get("shape_rank")
        if row.get("metadata_status") != "KNOWN" or kind is None or rank is None:
            return None, f"{label}: the engine reported no value metadata (metadata_status={row.get('metadata_status')!r})"
        if kind == "int64":
            return None, f"{label}: value kind int64 has no verified setter in the published layer"

        def scalar(item: Any) -> Any:
            if kind == "boolean":
                if isinstance(item, bool):
                    return item
                return str(item).strip().lower() in {"on", "true", "1"}
            if kind == "int32":
                return int(item)
            if kind == "float64":
                return float(item)
            if kind in {"string", "expression"}:
                return item if isinstance(item, str) else json.dumps(item) if isinstance(item, (list, dict)) else str(item)
            raise ValueError(f"unsupported kind {kind!r}")

        try:
            if rank == 0:
                return scalar(value), None
            if rank == 1:
                items = list(value) if isinstance(value, (list, tuple)) else [value]
                return [scalar(item) for item in items], None
            rows = list(value) if isinstance(value, (list, tuple)) else [value]
            return [[scalar(item) for item in (list(row) if isinstance(row, (list, tuple)) else [row])]
                    for row in rows], None
        except (TypeError, ValueError) as exc:
            return None, f"{label}: value {value!r} does not fit the engine's {kind!r} (rank {rank}) metadata ({exc})"

    async def set_properties(self, step: str, operation: str, path: Mapping[str, Any],
                             wanted: Mapping[str, Any], *, key: str, notes: str | None = None,
                             extra: Mapping[str, Any] | None = None,
                             metadata_path: Mapping[str, Any] | None = None,
                             documented: Mapping[str, Any] | None = None,
                             readback_path: Mapping[str, Any] | None = None,
                             required: bool = True) -> dict[str, Any]:
        """Write properties through the engine's metadata: read the schema, then update.

        ``metadata_path`` is where the *metadata* lives when that is not the node
        being written (a material's properties are described by its property
        *group*, not by the material node itself).  ``documented`` is the
        documented value shape for names the engine publishes no metadata for -
        the product types such a value from its own table, so the fixture passes
        the expression text verbatim and records ``value_source`` instead of
        refusing to write at all; a name that is neither known to the engine nor
        documented is still refused here.

        ``extra`` carries operation-specific arguments the published contract
        requires in addition to ``path``/``properties`` (``material.set_properties``
        needs its property ``group``, for example).
        """
        schema = await self.read_schema(metadata_path or path, wanted.keys(), key=key + "-schema")
        documented = dict(documented or {})
        if not schema and not documented:
            return self.record(step, f"{operation} (property write)", None, status="SKIPPED",
                               notes=f"{notes or ''} the engine returned no property metadata for "
                                     f"{sorted(wanted)}".strip())
        values: dict[str, Any] = {}
        refusals: list[str] = []
        detail: dict[str, Any] = {}
        for name, value in wanted.items():
            row = schema.get(name)
            if row is not None:
                coerced, refusal = self.coerce(value, row, name)
                if refusal:
                    refusals.append(refusal)
                    continue
                values[name] = coerced
                detail[name] = {"requested": coerced, "value_source": "engine_metadata",
                                "engine_kind": row.get("kind"),
                                "engine_shape_rank": row.get("shape_rank"),
                                "engine_value_type": row.get("value_type")}
                continue
            if name in documented:
                values[name] = value
                detail[name] = {"requested": self.driver._json_safe(value), "value_source": "documented_table",
                                "documented": dict(documented[name]),
                                "engine_kind": None, "engine_shape_rank": None,
                                "engine_value_type": None}
                continue
            refusals.append(f"{name}: the target node does not expose this property")
        if not values:
            return self.record(step, f"{operation} (property write)", None, status="SKIPPED",
                               notes="; ".join(refusals) or "no writable property was found")
        body: dict[str, Any] = {"path": dict(path), "properties": values, **dict(extra or {})}
        payload = await self.action(operation, body, key=key)
        readback = None
        applied = self.driver._success(payload)
        if applied:
            target = readback_path or metadata_path or path
            readback_payload = await self.action("node.property_get",
                                                 {"path": dict(target), "names": list(values)},
                                                 key=key + "-readback")
            readback = self.driver._json_safe(self.driver._data(readback_payload))
            if not self.driver._success(readback_payload):
                refusals.append("the write applied but the post-write readback was refused")
        notes_all = "; ".join([refusals[0]] if refusals and not applied else []) if refusals else notes
        row = self.record(step, operation, payload, notes=notes_all,
                          extra={"written": detail, "refused": refusals, "readback": readback,
                                 "request_arguments": sorted(body)})
        if required and not applied:
            row["required_write_failed"] = True
        return row

    # -- build ------------------------------------------------------------

    async def build(self, host: Any, client: Any) -> int:
        self.host, self.client = host, client
        args, driver = self.args, self.driver

        connect = await host.call("server_connect", {
            "host": args.host, "port": args.port,
            "execution": driver._execution(key="fixture-connect", request="fixture-connect"),
        })
        if not driver._success(connect):
            reason = f"server_connect failed: {driver._error_code(connect) or 'UNKNOWN'}"
            self.record("server_connect", "server_connect", connect, status="BLOCKED", notes=reason)
            raise FixtureBlocked(reason)
        self.record("server_connect", "server_connect", connect,
                    notes="engine connection established before the build steps")
        # The session's own deployment facts, read off the connect payload: the
        # ``trusted_code`` permission is an operator opt-in (COMSOL_MCP_TRUSTED_CODE)
        # and is never implied by a successful connection.  Recording it here keeps
        # the result-node step's blocker evidence in the same receipt.
        connect_data = driver._data(connect)
        trusted = connect_data.get("trusted_code") if isinstance(connect_data.get("trusted_code"), Mapping) else {}
        self.routing["session"] = {"session_id": connect_data.get("session_id"),
                                   "trusted_code": driver._json_safe(dict(trusted)) or None,
                                   "trusted_code_enabled": bool(trusted.get("enabled")),
                                   "tool_profile": args.tool_profile}

        created = await driver._create_empty_model(client, self.state, args.label, host)
        ref = self.state.get("ref") if isinstance(self.state.get("ref"), Mapping) else None
        self.record("model_create", "model_create", created,
                    notes="legacy published route: the strict model.create operation is not implemented",
                    extra={"execution": driver._json_safe(driver._envelope_identity(created)),
                           "model_ref": driver._json_safe(ref)})
