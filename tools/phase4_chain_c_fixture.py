def missing_dependency_plan() -> dict[str, Any]:
    """The minimal, reproducible path to a real missing-dependency model.

    Everything that can be decided without an engine is decided here: the step
    list, the source file's bytes, the published operations each step needs, and
    the two *external* facts that decide whether a live build is possible at all -
    the trusted-code permission and the CAD product a CAD-import sub-item would
    need.  The plan never claims the file exists: producing it needs a live build.
    """
    return {
        "kind": "phase4-t034-missing-dependency-plan",
        "output": MISSING_DEPENDENCY_FILE_NAME,
        "source": {"name": MISSING_DEPENDENCY_SOURCE_NAME,
                   "content": MISSING_DEPENDENCY_SOURCE_CONTENT,
                   "sha256": hashlib.sha256(MISSING_DEPENDENCY_SOURCE_CONTENT.encode()).hexdigest()},
        "steps": [dict(item) for item in MISSING_DEPENDENCY_MINIMUM_STEPS],
        "operations": sorted({item["operation"] for item in MISSING_DEPENDENCY_MINIMUM_STEPS
                              if item.get("operation")}),
        "function_tag": MISSING_DEPENDENCY_FUNCTION_TAG,
        "engine_side_artifact": {"source_artifact": MISSING_DEPENDENCY_SOURCE_ARTIFACT,
                                 "entrypoint": MISSING_DEPENDENCY_ENTRYPOINT,
                                 "route": "operation_call -> %s" % TRUSTED_CODE_OPERATION,
                                 "blocked_without": [TRUSTED_CODE_ENV]},
        "external_sub_items": {
            "interpolation_file_dependency": {
                "status": "EXTERNALLY_BLOCKED_OFFLINE",
                "reason": "producing the .mph needs a live engine: the container is written by COMSOL itself",
                "produced_by": "tools/phase4_run_mcp.py --only W14_T034_local_paths (live) or the Java artifact "
                               "through the trusted-code route",
            },
            "cad_import": {
                "status": "EXTERNALLY_BLOCKED_WITHOUT_A_CAD_PRODUCT",
                "reason": "the CAD sub-item needs a CAD Import product; the recorded model's own "
                          "usedlicenses.txt lists CADIMPORT, and without that product only this sub-item "
                          "is blocked - the interpolation-file dependency is product-independent",
            },
        },
        "offline_tools": {"inspect": f"--inspect-missing-dependency <path>",
                          "produce_from_donor": f"--missing-dependency-donor <mph> "
                                                f"--missing-dependency-out <dir>"},
        "unverified": [
            "no .mph is produced offline: a COMSOL model container is written by the engine",
            "a container produced from a donor records the dangling file dependency but has not been loaded "
            "by COMSOL: that a load reports it stays unverified until a live reload runs",
        ],
    }


def _container_view(path: Path) -> dict[str, Any]:
    """Read a candidate container's identity without trusting its name."""
    view: dict[str, Any] = {"path": str(path), "exists": path.is_file()}
    if not path.is_file():
        view["is_container"] = False
        return view
    view["bytes"] = path.stat().st_size
    view["sha256"] = _sha256(path)
    head = path.read_bytes()[: len(MISSING_DEPENDENCY_PROBE_BYTES)]
    if head == MISSING_DEPENDENCY_PROBE_BYTES:
        view.update({"is_container": False, "probe": True,
                     "probe_bytes": MISSING_DEPENDENCY_PROBE_BYTES.decode(),
                     "note": "the recorded runs left this text probe where the model should be"})
        return view
    try:
        with zipfile.ZipFile(path) as archive:
            names = archive.namelist()
            view["is_container"] = "fileversion" in names
            view["members"] = sorted(names)
            if "fileversion" in names:
                view["fileversion"] = archive.read("fileversion").decode("utf-8", "replace").strip()
            if "usedlicenses.txt" in names:
                view["used_licenses"] = sorted(line.strip() for line in
                                               archive.read("usedlicenses.txt").decode("utf-8", "replace").splitlines()
                                               if line.strip())
    except (zipfile.BadZipFile, OSError) as exc:
        view.update({"is_container": False, "error": f"{type(exc).__name__}: {exc}"})
    return view


def _dependency_record(container: Path, member: str = MISSING_DEPENDENCY_AUXILIARY_MEMBER) -> dict[str, Any]:
    """The container's own external-file dependency record, if it has one."""
    try:
        with zipfile.ZipFile(container) as archive:
            if member not in archive.namelist():
                return {"found": False, "reason": f"{member} is not in the container"}
            payload = json.loads(archive.read(member).decode("utf-8", "replace"))
    except (zipfile.BadZipFile, OSError, json.JSONDecodeError) as exc:
        return {"found": False, "reason": f"{type(exc).__name__}: {exc}"}
    rows = payload.get("auxiliaryData") if isinstance(payload, dict) else None
    if not isinstance(rows, list):
        return {"found": False, "reason": f"{member} carries no auxiliaryData array", "raw": payload}
    for row in rows:
        if not isinstance(row, Mapping):
            continue
        entity = row.get("modelEntity") if isinstance(row.get("modelEntity"), Mapping) else {}
        path = str(entity.get("modelEntityPath") or "")
        if not path.startswith(MISSING_DEPENDENCY_FUNCTION_PREFIX):
            continue
        if str(row.get("name")) != MISSING_DEPENDENCY_FILE_PROPERTY:
            continue
        value = str(row.get("value") or "")
        target = Path(value).expanduser() if value else None
        return {"found": True, "model_entity_path": path, "property": MISSING_DEPENDENCY_FILE_PROPERTY,
                "value": value, "file_types": list(row.get("fileTypes") or []),
                "is_active": bool(row.get("isActive")), "is_input": bool(row.get("isInput")),
                "resolved_path": str(target) if target else None,
                "referenced_file_exists": bool(target and target.is_file()),
                "entry_count": len(rows)}
    return {"found": False, "reason": f"no {MISSING_DEPENDENCY_FUNCTION_PREFIX}* "
                                      f"{MISSING_DEPENDENCY_FILE_PROPERTY!r} entry in {member}",
            "entry_count": len(rows)}


def inspect_missing_dependency(candidate: Path) -> dict[str, Any]:
    """Validate a *candidate* missing-dependency model, offline.

    ``PASS`` means every claim that can be checked without an engine holds: the
    file is a COMSOL container, it records an external-file dependency for an
    interpolation function, and the file it references is absent.  A text probe,
    a random file and a container whose dependency is resolved all fail or stay
    ``NOT_RUN`` - none of them may be counted as the fixture.
    """
    candidate = Path(candidate).expanduser()
    view = _container_view(candidate)
    result: dict[str, Any] = {"kind": "phase4-t034-missing-dependency-inspection",
                             "candidate": str(candidate), "container": view}
    if not view.get("is_container"):
        return {**result, "status": "FAIL",
                "reason": ("the candidate is not a COMSOL container"
                           + (" (it is the recorded text probe)" if view.get("probe") else ""))}
    record = _dependency_record(candidate)
    result["dependency"] = record
    if not record.get("found"):
        return {**result, "status": "NOT_RUN",
                "reason": f"the container records no external-file dependency: {record.get('reason')}"}
    if not record.get("value"):
        return {**result, "status": "NOT_RUN",
                "reason": "the container's interpolation function references no file, so no dependency "
                          "can be missing (created container, or the file property was never set)"}
    if record.get("referenced_file_exists"):
        return {**result, "status": "NOT_RUN",
                "reason": f"the dependency is resolved: {record['resolved_path']} exists"}
    return {**result, "status": "PASS",
            "reason": f"the container records the interpolation function {record['model_entity_path']} "
                      f"depending on the absent file {record['value']}",
            "unverified": ["that COMSOL reports the dependency when it loads this file - that needs a live "
                           "reload and is the W14.T034 live sub-item"]}


def produce_missing_dependency(donor: Path, output: Path, *, source_path: Path,
                               overwrite: bool = False) -> dict[str, Any]:
    """Patch a real donor container so its interpolation file is absent.

    The donor is a container COMSOL itself wrote (``MISSING_DEPENDENCY_DONOR`` by
    default): it carries a real ``Interpolation`` function node and the
    ``auxiliaryData`` record of that node's file property.  Two text members are
    rewritten - the node's ``filename`` property in ``dmodel.xml`` and the
    recorded value in ``auxiliarydatainfo.json`` - and every other member is
    copied byte for byte, so the result stays a real container.  What cannot be
    checked offline (that a load reports the dependency) is recorded, never
    assumed.
    """
    donor, output, source_path = Path(donor).expanduser(), Path(output).expanduser(), Path(source_path).expanduser()
    result: dict[str, Any] = {"kind": "phase4-t034-missing-dependency-production",
                              "donor": {"path": str(donor), "exists": donor.is_file()},
                              "output": {"path": str(output)}, "referenced_file": str(source_path)}
    if not donor.is_file():
        return {**result, "status": "REFUSED", "reason": f"the donor container is missing: {donor}"}
    result["donor"]["sha256"] = _sha256(donor)
    view = _container_view(donor)
    result["donor"]["container"] = {key: view.get(key) for key in ("is_container", "fileversion", "used_licenses")}
    if not view.get("is_container"):
        return {**result, "status": "REFUSED",
                "reason": "the donor is not a COMSOL container, so nothing can be patched faithfully"}
    if output.exists() and not overwrite:
        return {**result, "status": "REFUSED",
                "reason": f"{output} exists; pass overwrite=True to replace it"}
    if not str(source_path):
        return {**result, "status": "REFUSED", "reason": "the referenced file path must not be empty"}

    try:
        with zipfile.ZipFile(donor) as archive:
            members = {name: archive.read(name) for name in archive.namelist()}
    except (zipfile.BadZipFile, OSError) as exc:
        return {**result, "status": "REFUSED", "reason": f"the donor could not be read: {type(exc).__name__}: {exc}"}
    for required in (MISSING_DEPENDENCY_MODEL_MEMBER, MISSING_DEPENDENCY_AUXILIARY_MEMBER):
        if required not in members:
            return {**result, "status": "REFUSED", "reason": f"the donor has no {required} member"}

    model_text = members[MISSING_DEPENDENCY_MODEL_MEMBER].decode("utf-8", "replace")
    node = re.search(r'<FunctionFeature op="Interpolation" tag="([^"]+)"', model_text)
    if node is None:
        return {**result, "status": "REFUSED",
                "reason": "the donor carries no Interpolation function node to depend on a file"}
    function_tag = node.group(1)
    if f'name="p:{MISSING_DEPENDENCY_FILE_PROPERTY}"' in model_text:
        return {**result, "status": "REFUSED",
                "reason": f"the donor already sets p:{MISSING_DEPENDENCY_FILE_PROPERTY}; patching it would "
                          f"hide the donor's own state instead of adding the dependency"}

    escaped = (str(source_path).replace("&", "&amp;").replace("<", "&lt;")
               .replace(">", "&gt;").replace('"', "&quot;"))
    anchor = re.search(r'(<FunctionFeature op="Interpolation" tag="%s"[^>]*>\s*'
                       r'<!-- User comments -->\s*<entityComments T="0">[^<]*</entityComments>\s*'
                       r'<!-- Created by -->\s*<entityAuthor T="0">[^<]*</entityAuthor>)' % re.escape(function_tag),
                       model_text)
    if anchor is None:
        return {**result, "status": "REFUSED",
                "reason": "the interpolation node's header could not be located in dmodel.xml"}
    injected = ('%s\n      <!-- Interpolation file (external dependency) -->\n'
                '      <propertyValue T="30" value="%s" name="p:%s"></propertyValue>'
                % (anchor.group(1), escaped, MISSING_DEPENDENCY_FILE_PROPERTY))
    patched_model = model_text[:anchor.start(1)] + injected + model_text[anchor.end(1):]

    try:
        payload = json.loads(members[MISSING_DEPENDENCY_AUXILIARY_MEMBER].decode("utf-8", "replace"))
    except json.JSONDecodeError as exc:
        return {**result, "status": "REFUSED", "reason": f"auxiliarydatainfo.json is not JSON: {exc}"}
    rows = payload.get("auxiliaryData") if isinstance(payload, dict) else None
    if not isinstance(rows, list):
        return {**result, "status": "REFUSED", "reason": "auxiliarydatainfo.json carries no auxiliaryData array"}
    patched_entry = None
    for row in rows:
        if not isinstance(row, dict):
            continue
        entity = row.get("modelEntity") if isinstance(row.get("modelEntity"), dict) else {}
        if str(entity.get("modelEntityPath") or "").startswith(MISSING_DEPENDENCY_FUNCTION_PREFIX) \
                and str(row.get("name")) == MISSING_DEPENDENCY_FILE_PROPERTY:
            row["value"] = str(source_path)
            patched_entry = {key: row[key] for key in ("name", "value", "fileTypes", "modelEntity")}
            break
    if patched_entry is None:
        return {**result, "status": "REFUSED",
                "reason": "the donor's auxiliary-data record has no interpolation file entry to point at the "
                          "absent path"}
    patched_aux = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8")

    output.parent.mkdir(parents=True, exist_ok=True)
    members[MISSING_DEPENDENCY_MODEL_MEMBER] = patched_model.encode("utf-8")
    members[MISSING_DEPENDENCY_AUXILIARY_MEMBER] = patched_aux
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, data in members.items():
            archive.writestr(name, data)
    record = _dependency_record(output)
    inspection = inspect_missing_dependency(output)
    return {**result, "status": "PRODUCED", "function_tag": function_tag,
            "output": {"path": str(output), "sha256": _sha256(output), "bytes": output.stat().st_size,
                       "members": len(members)},
            "patch": {"members": [MISSING_DEPENDENCY_MODEL_MEMBER, MISSING_DEPENDENCY_AUXILIARY_MEMBER],
                      "model_property": f"p:{MISSING_DEPENDENCY_FILE_PROPERTY}",
                      "model_value": str(source_path),
                      "auxiliary_entry": patched_entry},
            "dependency_record": record,
            "inspection": inspection,
            "verified_offline": ["the output is a COMSOL container with the donor's members",
                                 "the interpolation node records the absent file",
                                 "the referenced file does not exist"],
            "unverified": ["that COMSOL reports the dependency when it loads this file - that needs a live "
                           "reload (the W14.T034 live sub-item); the recorded text probe this replaces is "
                           "detected by --inspect-missing-dependency"]}


def self_consistency() -> dict[str, Any]:
    """Offline self-check: plan integrity plus the pure decisions, replayed.

    Every decision the live build makes about *which* property/feature to write
    is made by a pure helper; this replays those helpers on the metadata recorded
    from the failed v11 build (kept unmodified as failure evidence) so the
    reasoning can be re-checked without an engine:

    * the recorded init feature publishes ``Tinit``/``Tinit_src`` and no ``T0``,
      so the property is selected from the engine's own vocabulary;
    * the recorded mesh feature is tagged ``size`` with ``type_id``
      ``MeshSizeDefault``, so it is found by tag/current-feature, not by type;
    * the recorded material *node* schema publishes none of the three property
      names, which is why the material write must not be gated on it;
    * the recorded deployment blocks the result-node route, and the same route is
      available once the two recorded blockers are removed.
    """
    steps = {item["step"] for item in PLAN_STEPS}
    required = {"study_step_transient", "study_step_tlist", "manual_solver_edit", "model_save",
                "result_nodes", "sibling_geometry", "physics_initial_values", "mesh_size"}
    missing = sorted(required - steps)

    init = RECORDED_METADATA["initial_values_feature"]
    init_choice = select_initial_temperature_property(init["properties"])
    mesh_choice = select_mesh_size_feature(RECORDED_METADATA["mesh_sequence"])
    material = RECORDED_METADATA["material_node"]
    material_names = {str(row.get("name")) for row in material["properties"]}
    material_gap = not (set(material["wanted_absent"]) & material_names)

    blocked = resolve_trusted_code_route(
        describe_status="SUPPORTED_UNVERIFIED", trusted_code_enabled=False, published_tools=(), profile="full",
        result_operations={name: "PROPOSED_NOT_IMPLEMENTED" for name in RESULT_NODE_OPERATIONS})
    unblocked = resolve_trusted_code_route(
        describe_status="SUPPORTED_UNVERIFIED", trusted_code_enabled=True, published_tools=(), profile="expert",
        result_operations={name: "SUPPORTED" for name in RESULT_NODE_OPERATIONS})
    checks: dict[str, Any] = {
        "plan_steps": len(PLAN_STEPS),
        "missing_plan_steps": missing,
        "initial_temperature_property": init_choice["property"],
        "initial_temperature_source_property": init_choice["source_property"],
        "initial_temperature_absent_candidates": init_choice["absent"],
        "mesh_size_feature": mesh_choice["tag"],
        "mesh_size_selection_rule": mesh_choice["rule"],
        "material_node_publishes_no_property_group_names": material_gap,
        "result_route_available_on_a_blocked_deployment": blocked["available"],
        "result_route_blocker_kinds": [item["kind"] for item in blocked["blockers"]],
        "result_route_available_when_unblocked": unblocked["available"],
        "recorded_metadata_source": RECORDED_METADATA["source"],
    }
    ok = (not missing and init_choice["property"] == "Tinit" and init_choice["source_property"] == "Tinit_src"
          and mesh_choice["tag"] == "size" and material_gap
          and blocked["available"] is False and unblocked["available"] is True)
    return {**checks, "ok": bool(ok)}


def driver_arguments(args: argparse.Namespace) -> argparse.Namespace:
    """Translate this script's CLI into the driver's own Namespace (same env conventions)."""
    translator = load_driver().build_parser()
    argv = ["--python", str(args.python), "--host", str(args.host), "--port", str(args.port),
            "--project-id", str(args.project_id), "--tool-profile", str(args.tool_profile),
            "--run-dir", str(Path(args.run_dir).expanduser())]
    if args.comsol_root:
        argv += ["--comsol-root", str(args.comsol_root)]
    if args.jdk11:
        argv += ["--jdk11", str(args.jdk11)]
    if args.prefs:
        argv += ["--prefs", str(args.prefs)]
    if args.private_home:
        argv += ["--private-home", str(Path(args.private_home).expanduser())]
    if args.live:
        argv += ["--live"]
    return translator.parse_args(argv)


def default_run_dir() -> Path:
    return ROOT / "evidence" / "phase4" / "chain_c_fixture" / _stamp()


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(list(argv) if argv is not None else None)
    validate(args, parser)
    if args.dry_run:
        print_plan(args)
        print("dry run: no COMSOL Server, no MCP session, no files")
        return 0
    if args.self_check:
        result = self_consistency()
        print(json.dumps(result, indent=2, sort_keys=True))
        print(f"self-check: {'ok' if result['ok'] else 'FAILED'} "
              f"(no COMSOL Server, no MCP session, no files)")
        return 0 if result["ok"] else 1
    if args.missing_dependency_plan:
        print(json.dumps(missing_dependency_plan(), indent=2, sort_keys=True, ensure_ascii=False))
        print("missing-dependency plan: no COMSOL Server, no MCP session, no file written")
        return 0
    if args.inspect_missing_dependency is not None:
        result = inspect_missing_dependency(args.inspect_missing_dependency)
        print(json.dumps(result, indent=2, sort_keys=True, ensure_ascii=False))
        print(f"missing-dependency inspection: {result['status']} - {result['reason']}")
        return {"PASS": 0, "NOT_RUN": 2}.get(result["status"], 1)
    if args.missing_dependency_donor is not None:
        out_dir = Path(args.missing_dependency_out).expanduser()
        output = out_dir / MISSING_DEPENDENCY_FILE_NAME
        source = (Path(args.missing_dependency_source).expanduser() if args.missing_dependency_source
                  else out_dir / MISSING_DEPENDENCY_SOURCE_NAME)
        result = produce_missing_dependency(args.missing_dependency_donor, output, source_path=source,
                                            overwrite=args.overwrite)
        print(json.dumps(result, indent=2, sort_keys=True, ensure_ascii=False))
        print(f"missing-dependency production: {result['status']} - "
              f"{result.get('reason') or result['output']['path']}")
        return 0 if result["status"] == "PRODUCED" else 2
    if args.run_dir is None:
        args.run_dir = str(default_run_dir())
    if args.output is None:
        args.output = Path(args.run_dir).expanduser() / "chain_c_user_style.mph"
    try:
        driver = load_driver()
    except FixtureError as exc:
        print(f"error: {exc}")
        return 2
    driver_args = driver_arguments(args)
    if not driver_args.live and not args.handshake_only:
        print("error: --live is required to build the fixture (or use --handshake-only / --dry-run)")
        return 2
    fixture = ChainCFixture(args, driver, driver_args)
    print(f"phase4 chain C fixture -> {fixture.run_dir}")
    try:
        code = asyncio.run(fixture.run(handshake_only=args.handshake_only))
    except KeyboardInterrupt:
        return 130
    print(f"exit code {code}")
    return code


if __name__ == "__main__":
    sys.exit(main())
